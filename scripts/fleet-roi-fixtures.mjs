// Writes tests/fixtures/fleet-roi-cases.json: Fleet ROI 2.0 inputs and the
// outputs public/js/fleet-roi.js gives for them. Both the node test
// (tests/fleet-roi.test.mjs) and the iOS test (FleetROIModelTests.swift)
// check their model against this file, so the two can't drift apart.
// Regenerate ONLY when the model changes on purpose (and say why in the
// commit):  node scripts/fleet-roi-fixtures.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const R = require('../public/js/fleet-roi.js');

const cases = {
  'fleet, 1 vehicle, cash, defaults': {},
  'personal ownership, cash, defaults': { mode: 'personal' },
  'personal ownership, financed': { mode: 'personal', purchase: 'finance' },
  'fleet, 1 vehicle, financed 20% down 6.9% 60 mo': { purchase: 'finance' },
  'fleet, 100 vehicles, financed': { vehicles: 100, purchase: 'finance', downPaymentPct: 10, aprPct: 7.5, loanMonths: 72 },
  'fleet, 1000 vehicles, cash, optimistic': R.withScenario({ vehicles: 1000 }, 'optimistic'),
  'fleet, 5 vehicles, conservative': R.withScenario({ vehicles: 5 }, 'conservative'),
  'fleet, zero revenue (fare $0)': { farePerRide: 0 },
  'fleet, negative cash flow (low use, high costs)': { ridesPerDay: 3, insuranceMonthly: 600, purchase: 'finance' },
  'fleet, 80% downtime': { downtimePct: 80 },
  'fleet, 100% downtime': { downtimePct: 100 },
  'fleet, 0% APR financing': { purchase: 'finance', aprPct: 0, downPaymentPct: 0, loanMonths: 36 },
  'fleet, commercial start 24 months after delivery': { activationDelayMonths: 24 },
  'fleet, no included subscription month': { subscriptionIncludedMonths: 0 },
  'fleet, 10-year horizon': { horizonMonths: 120, vehicles: 10 },
  'invalid inputs fall back or clamp': { mode: 'robotaxi', vehicles: -4, price: 'abc', farePerRide: 1e9, purchase: 'lease', aprPct: Number.NaN, ridesPerDay: '20', horizonMonths: 7 },
};

const pick = r => ({
  input: r.input,
  purchase: r.purchase,
  perVehicle: r.perVehicle,
  steady: r.steady,
  horizon: r.horizon,
  paybackMonth: r.paybackMonth,
  loanBalanceAtPayback: r.loanBalanceAtPayback,
  cumulativeEnd: r.cumulativeEnd,
  month1: r.months[0],
  month12: r.months[11],
  month60: r.months[59],
});

const out = Object.entries(cases).map(([name, input]) => ({ name, input, expected: pick(R.simulate(input)) }));
// JSON can't hold NaN: the invalid case writes it as null (also invalid).
const json = JSON.stringify({ about: 'Fleet ROI 2.0 shared fixtures; generated by scripts/fleet-roi-fixtures.mjs from public/js/fleet-roi.js. Do not edit by hand.', model: 'docs/fleet-roi-model.md', cases: out }, null, 1);
fs.writeFileSync(new URL('../tests/fixtures/fleet-roi-cases.json', import.meta.url), json + '\n');
console.log(`${out.length} cases written`);
